"""Versioned KerOp → SpecInv forward-spectrum artifact.

KerOp learns a *forward* operator and can export its spectrum.  SpecInv consumes
that spectrum as the singular values of a compact inverse problem and learns a
spectral filter.  This module is the contract between the two: a small, versioned
``npz`` / ``json`` payload — not a new theorem and not a substitute for either
repository's own bar.

Schema ``kerop.specinv.spectrum/v1``
------------------------------------
Required fields (see ``docs/KEROP_SPECTRUM.md``):

* ``eigenvalues`` — 1-D positive, non-increasing forward spectrum used as
  SpecInv singular values (KerOp input-mode weights, or a 1-D RF spectrum)
* ``operator_id`` — stable id of the KerOp instance that produced the array
* ``seed`` — KerOp model seed
* ``n`` — number of exported modes
* ``feature_count`` — random-feature count ``M`` attached to this export

The payload may also carry the flattened product-set RF spectrum, the
``(r, b)`` pair, and the implied ill-posedness ``p = 1/b``.

This module can *write* an artifact only by importing KerOp and calling
``SpectralOperatorModel``.  A committed fixture is allowed as a load path, but
it must have been generated by :func:`export_kerop_spectrum`.
"""

